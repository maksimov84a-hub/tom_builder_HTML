# -*- coding: utf-8 -*-
"""Каноническая геометрия основной надписи (ГОСТ Р 21.101-2020, приложение Ж).

Единый источник размеров (в мм) и сетки форм основной надписи:
  форма 3 (лист графической части)   — 185 x 55;
  форма 5 (первый лист текстового)   — 185 x 40;
  форма 6 (последующие листы текста) — 185 x 15.

Сетки выверены по образцам (Форма 3/5/6.pdf) и согласованы с HTML-предпросмотром
(preview_html.py). Используется при отрисовке в Word (docx_exporter.py) и PDF
(renderer.py), чтобы геометрия штампов совпадала во всех выводах.

Каждая форма описывается списком вертикальных/горизонтальных линий сетки (мм от
левого-верхнего угла штампа) и набором ячеек (col_span, row_span, роль, ключ).
"""
from __future__ import annotations

# Ширина основной надписи (внутренняя ширина рамки, стандарт 185 мм)
STAMP_WIDTH_MM = 185.0

# Высота основной надписи по форме (номера форм ГОСТ: 3 / 5 / 6)
FORM_HEIGHT = {3: 55.0, 5: 40.0, 6: 15.0}

# ---- Таблица изменений (графы 14–19): 6 колонок, сумма 65 мм ----------------
CHANGE_COLS = [10.0, 10.0, 10.0, 10.0, 15.0, 10.0]
CHANGE_LABELS = ["Изм.", "Кол.уч", "Лист", "№док.", "Подп.", "Дата"]
CHANGE_KEYS = ["ch", "col", "sheet", "docno", "sign", "date"]
CHANGE_W = sum(CHANGE_COLS)   # 65 мм

# Правая узкая колонка «Лист» (графы 7, 8) — 10 мм
SHEET_COL_W = 10.0


# ---- Графа 9 (наименование / различительный индекс организации) ---------------
# ГОСТ Р 21.101-2020, приложение Ж: графа 9 — правая верхняя ячейка основной
# надписи форм 5 и 3. В форме 6 графы 9 нет.
#   форма 5: x 135..185, y 15..25 мм от левого-верхнего угла штампа (50 x 10);
#   форма 3: x 135..185, y 40..55 мм (50 x 15).
#: ключи ячеек графы 9 в сетках форм (единый список для Word и PDF).
CELL9_KEYS = ("organization", "cell9", "stamp9")
CELL9_PT = 12                 # кегль текста графы 9 (как «Стадия / Лист / Листов»)


# ---- Кегль граф «Стадия / Лист / Листов» -------------------------------------
# Надписи и значения этих граф в основной надписи (формы 3, 5, 6 ГОСТ)
# набираются единым кеглем 12 pt.
STAGE_CELL_PT = 12
#: ключи ячеек, кегль которых задаётся STAGE_CELL_PT.
STAGE_CELL_KEYS = ("stage", "sheet", "qty")


# ---- Форма 6 (185 x 15) ------------------------------------------------------
# vlines: [0,10,20,30,40,55,65,175,185]  → 8 колонок
# hlines (объединение левого блока и колонки «Лист»): [0,5,7,10,15]
F6_VLINES = [0.0, 10.0, 20.0, 30.0, 40.0, 55.0, 65.0, 175.0, 185.0]
F6_HLINES = [0.0, 5.0, 7.0, 10.0, 15.0]
F6_DESIGN_W = 110.0   # 65..175


# ---- Форма 5 (185 x 40) ------------------------------------------------------
# vlines: [0,10,20,30,40,55,65,135,150,165,185]  → 10 колонок
# hlines (объединение левого блока и правого): [0,5,10,15,20,25,30,35,40]
F5_VLINES = [0.0, 10.0, 20.0, 30.0, 40.0, 55.0, 65.0, 135.0, 150.0, 165.0, 185.0]
F5_HLINES = [0.0, 5.0, 10.0, 15.0, 20.0, 25.0, 30.0, 35.0, 40.0]


# ---- Форма 3 (185 x 55) ------------------------------------------------------
F3_VLINES = [0.0, 10.0, 20.0, 30.0, 40.0, 55.0, 65.0, 135.0, 150.0, 165.0, 185.0]
F3_HLINES = [0.0, 5.0, 10.0, 15.0, 20.0, 25.0, 30.0, 35.0, 40.0, 45.0, 50.0, 55.0]


# ---- Ячейки (для Word-таблицы) ----------------------------------------------
# Каждая ячейка: (col0, col1, row0, row1, role, key, label)
#   col0..col1 — диапазон колонок (индексы по vlines), row0..row1 — по hlines.
#   role: 'change_hdr' | 'change_val' | 'design' | 'sheet_hdr' | 'sheet_val' |
#         'label' (статичный) | 'field' (значение из реквизитов).

def form6_cells():
    """Ячейки формы 6 (185 x 15)."""
    cells = []
    # Таблица изменений: заголовок (row 0..1 = y 0..5), значения (row 1..4 = y 5..15)
    for ci in range(6):
        cells.append((ci, ci + 1, 0, 1, "change_hdr", CHANGE_KEYS[ci], CHANGE_LABELS[ci]))
    for ci in range(6):
        cells.append((ci, ci + 1, 1, 4, "change_val", CHANGE_KEYS[ci], ""))
    # Обозначение (65..175), на всю высоту (row 0..4)
    cells.append((6, 7, 0, 4, "design", "volume", ""))
    # Колонка «Лист»: заголовок (row 0..2 = y 0..7), значение (row 2..4 = y 7..15)
    cells.append((7, 8, 0, 2, "sheet_hdr", "", "Лист"))
    cells.append((7, 8, 2, 4, "sheet_val", "sheet", ""))
    return cells


def form5_cells():
    """Ячейки формы 5 (185 x 40).

    Колонки (по F5_VLINES): 0..9 → 10 колонок.
      0: 0-10  (Изм)   1: 10-20 (Кол.уч)  2: 20-30 (Лист)
      3: 30-40 (№док.)  4: 40-55 (Подп.)   5: 55-65 (Дата)
      6: 65-135 (обозначение / наименование)
      7: 135-150 (Стадия)  8: 150-165 (Лист)  9: 165-185 (Листов)
    """
    cells = []
    # Таблица изменений: заголовок (row 2..3 = y 10..15), значения (row 3..4 = y 15..20)
    for ci in range(6):
        cells.append((ci, ci + 1, 2, 3, "change_hdr", CHANGE_KEYS[ci], CHANGE_LABELS[ci]))
    for ci in range(6):
        cells.append((ci, ci + 1, 3, 4, "change_val", CHANGE_KEYS[ci], ""))
    # Строки подписей: Разраб. (y20..25), Н.контр. (y30..35), ГИП (y35..40)
    sig_rows = [("Разраб.", "develop", 20.0), ("Н.контр.", "norm", 30.0), ("ГИП", "approve", 35.0)]
    for label, key, y in sig_rows:
        r0 = int(round(y / 5.0))   # 20->4, 30->6, 35->7
        r1 = r0 + 1
        cells.append((0, 2, r0, r1, "label", "", label))          # должность
        cells.append((2, 5, r0, r1, "sig", key, ""))              # фамилия/подпись
        cells.append((5, 6, r0, r1, "change_val", "date", ""))    # дата
    # Обозначение (65..135) y 0..15 (row 0..3)
    cells.append((6, 7, 0, 3, "design", "volume", ""))
    # Стадия | Лист | Листов (135..185) y 15..20 (row 3..4) — заголовки
    cells.append((7, 8, 3, 4, "label", "", "Стадия"))
    cells.append((8, 9, 3, 4, "label", "", "Лист"))
    cells.append((9, 10, 3, 4, "label", "", "Листов"))
    # Стадия | Лист | Листов (135..185) y 20..25 (row 4..5) — значения
    cells.append((7, 8, 4, 5, "field", "stage", ""))
    cells.append((8, 9, 4, 5, "field", "sheet", ""))
    cells.append((9, 10, 4, 5, "field", "qty", ""))
    # Наименование документа (65..135) y 15..40 (row 3..8)
    cells.append((6, 7, 3, 8, "field", "name", ""))
    # Организация (135..185) y 25..40 (row 5..8)
    cells.append((7, 10, 5, 8, "field", "organization", ""))
    return cells


def form3_cells():
    """Ячейки формы 3 (185 x 55) — упрощённо как форма 5 с большей высотой."""
    return form5_cells()


def grid(form: int) -> dict:
    """Возвращает сетку (vlines, hlines) и ячейки для формы form (3/5/6)."""
    if form == 6:
        return {"vlines": F6_VLINES, "hlines": F6_HLINES, "cells": form6_cells()}
    if form == 3:
        return {"vlines": F3_VLINES, "hlines": F3_HLINES, "cells": form3_cells()}
    # форма 5 (по умолчанию)
    return {"vlines": F5_VLINES, "hlines": F5_HLINES, "cells": form5_cells()}
